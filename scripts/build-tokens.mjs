// tokens/tokens.json → src/styles/tokens.css (generated, gitignored).
// Rules: {dark,light} value → per theme; plain string → both; "{name}" → var(--name).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const t = JSON.parse(readFileSync(resolve(root, "tokens/tokens.json"), "utf8"));
const themes = t.color.themes.map((x) => x.id); // ["dark", "light"]
const out = Object.fromEntries(themes.map((id) => [id, []]));
const shared = [];

const ref = (v) => (typeof v === "string" ? v.replace(/^\{([a-z0-9-]+)\}$/, "var(--$1)") : String(v));
function add(name, value) {
  if (value && typeof value === "object") {
    for (const id of themes) if (value[id] != null) out[id].push(`  --${name}: ${ref(value[id])};`);
  } else {
    shared.push(`  --${name}: ${ref(value)};`);
  }
}

for (const tok of t.color.tokens) add(tok.name, tok.value);
for (const [k, v] of Object.entries(t.type.families ?? {})) {
  add(`font-${k}`, v);
  add(`x-font-${k}`, `{font-${k}}`); // alias: the xDev app uses the x- prefixed names
}
for (const group of ["spacing", "radius", "size", "shadow"]) for (const tok of t[group]?.tokens ?? []) add(tok.name, tok.value);

const [first, ...rest] = themes;
let css = `/* Generated by scripts/build-tokens.mjs from tokens/tokens.json (${t.name} ${t.version}). Do not edit. */\n`;
css += `:root {\n${shared.join("\n")}\n}\n`;
css += `:root,\n[data-theme="${first}"] {\n  color-scheme: ${first};\n${out[first].join("\n")}\n}\n`;
for (const id of rest) css += `[data-theme="${id}"] {\n  color-scheme: ${id};\n${out[id].join("\n")}\n}\n`;

const dest = resolve(root, "src/styles/tokens.css");
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, css);
console.log(`tokens.css: ${shared.length} shared, ${themes.map((id) => `${out[id].length} ${id}`).join(", ")}`);
