// tokens/tokens.json → src/styles/tokens.css (generated, gitignored).
// Rules: {dark,light} value → per theme; plain string → both; "{name}" → var(--name).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const t = JSON.parse(readFileSync(resolve(root, "tokens/tokens.json"), "utf8"));
const themes = t.color.themes.map((x) => x.id); // ["dark", "light"]
const out = Object.fromEntries(themes.map((id) => [id, []]));
const shared = [];

const ref = (v) => (typeof v === "string" ? v.replace(/^\{([a-z0-9-]+)\}$/, "var(--$1)") : String(v));
function add(name, value) {
  if (value && typeof value === "object") {
    for (const id of themes) if (value[id] != null) out[id].push(`  --${name}: ${ref(value[id])};`);
  } else {
    shared.push(`  --${name}: ${ref(value)};`);
  }
}

for (const tok of t.color.tokens) add(tok.name, tok.value);
for (const [k, v] of Object.entries(t.type.families ?? {})) {
  add(`font-${k}`, v);
  add(`x-font-${k}`, `{font-${k}}`); // alias: the xDev app uses the x- prefixed names
}
for (const group of t.type.groups ?? []) {
  for (const st of group.styles ?? []) {
    add(`type-${st.name}`, `${st.fontWeight ?? 400} ${st.fontSize}${st.lineHeight ? `/${st.lineHeight}` : ""} var(--font-${group.family})`);
  }
}
for (const group of ["spacing", "radius", "size", "shadow", "zIndex", "breakpoint"]) for (const tok of t[group]?.tokens ?? []) add(tok.name, tok.value);

const [first, ...rest] = themes;
let css = `/* Generated by scripts/build-tokens.mjs from tokens/tokens.json (${t.name} ${t.version}). Do not edit. */\n`;
css += `:root {\n${shared.join("\n")}\n}\n`;
css += `:root,\n[data-theme="${first}"] {\n  color-scheme: ${first};\n${out[first].join("\n")}\n}\n`;
for (const id of rest) css += `[data-theme="${id}"] {\n  color-scheme: ${id};\n${out[id].join("\n")}\n}\n`;

// prefers-contrast: more strengthens hairlines and secondary text. Values reference tokens only; :root[data-theme] outranks the theme blocks above.
if (t.color.contrastMore?.length) {
  const decls = t.color.contrastMore.map((x) => `    --${x.name}: ${ref(x.value)};`).join("\n");
  css += `@media (prefers-contrast: more) {\n  :root,\n  :root[data-theme] {\n${decls}\n  }\n}\n`;
}

const dest = resolve(root, "src/styles/tokens.css");
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, css);
console.log(`tokens.css: ${shared.length} shared, ${themes.map((id) => `${out[id].length} ${id}`).join(", ")}`);

// tokens.json → src/styles/tailwind.css (generated): a Tailwind v4 theme over the same tokens.
// Colours and radii point at the xdev variables (@theme inline), so the light/dark switch
// keeps working; fonts and breakpoints are literal because Tailwind's names (--font-mono) clash.
// Shadows are not mapped (same names would point at themselves): use shadow-(--shadow-menu).
// Spacing is left alone: Tailwind's 0.25rem step equals --x-space-1, so p-4 = --x-space-4.
const rem = (px) => `${parseFloat(px) / 16}rem`;
const tw = [];
tw.push(`/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit. */`);
tw.push(`/* Tailwind v4 theme for @xdev-asia/ui. Import after "tailwindcss" and "@xdev-asia/ui/styles.css". */`);
tw.push(`@theme {`);
for (const tok of t.breakpoint?.tokens ?? []) tw.push(`  --breakpoint-${tok.name.replace(/^x-bp-/, "")}: ${rem(tok.value)};`);
for (const [k, v] of Object.entries(t.type.families ?? {})) if (k !== "body-fallback") tw.push(`  --font-${k === "body" ? "sans" : k}: ${v};`);
tw.push(`}`);
tw.push(`@theme inline {`);
const colorNames = [...new Set(t.color.tokens.map((x) => x.name).filter((n) => n.startsWith("x-color-")))];
for (const n of colorNames) tw.push(`  --color-${n.replace(/^x-color-/, "")}: var(--${n});`);
for (const tok of (t.radius?.tokens ?? []).filter((x) => x.name.startsWith("x-radius-"))) tw.push(`  --radius-${tok.name.replace(/^x-radius-/, "")}: var(--${tok.name});`);
tw.push(`}`);
writeFileSync(resolve(root, "src/styles/tailwind.css"), tw.join("\n") + "\n");
console.log(`tailwind.css: ${colorNames.length} colours`);
